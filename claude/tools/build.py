def counts(ch):
    m = b = n = 0
    for _, _, entries in ch["sections"]:
        for e in entries:
            if e["kind"] == "boss":
                b += 1
            elif e["kind"] == "item":
                n += 1
                if e["miss"] or "miss" in e["tags"]:
                    m += 1
    return m, b, n


